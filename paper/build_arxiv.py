"""Build the arXiv preprint from the single source latex/main.tex (anonymous ACL version).

Changes: preprint option, author, figure paths, code URL at the end of the abstract, self-live footnote.
Output: arxiv/main.tex, arxiv/main.pdf, arxiv/main.bbl, arxiv/arxiv.tar.gz (main.tex, main.bbl, acl.sty, acl_natbib.bst,
figs/*.pdf) and arxiv/ARXIV_SUBMISSION.md (metadata with the abstract as plain text). Needs tectonic and pdfinfo.

usage: python paper/build_arxiv.py
"""
import re
import shutil
import subprocess
import tarfile
from pathlib import Path

P = Path(__file__).resolve().parent
SRC, OUT = P / "latex", P / "arxiv"
URL = "https://github.com/yanghu819/untying-prefill-decode"

SUBS = [
    (r"\usepackage[review]{acl}", r"\usepackage[preprint]{acl}"),
    (r"\author{Anonymous ACL submission}", r"\author{Yang Hu}"),
    ("{../figs/", "{figs/"),
    ("\\end{abstract}", f"Code, results and per-item outputs: \\url{{{URL}}}.\n\\end{{abstract}}"),
    (r"(\emph{self-live},",
     r"(\emph{self-live}\footnote{Self-live was developed by the author in separate work on shared KV caches for looped"
     r" models; here it is applied to the connector's answer tokens.},"),
]


def main():
    tex = (SRC / "main.tex").read_text()
    for a, b in SUBS:
        assert a in tex, f"pattern not found in latex/main.tex: {a[:60]}"
        tex = tex.replace(a, b)
    # generated table rows (paper_figs.py tab_equal) are inlined so the arXiv source is one file
    tex = re.sub(r"\\csname @@input\\endcsname \.\./figs/(\S+\.tex)",
                 lambda m: (P / "figs" / m.group(1)).read_text().strip(), tex)
    OUT.mkdir(exist_ok=True)
    (OUT / "figs").mkdir(exist_ok=True)
    (OUT / "main.tex").write_text(tex)
    for f in ("acl.sty", "acl_natbib.bst", "references.bib"):
        shutil.copy(SRC / f, OUT / f)
    figs = sorted((P / "figs").glob("fig*.pdf"))
    for f in figs:
        shutil.copy(f, OUT / "figs" / f.name)
    subprocess.run(["tectonic", "-X", "compile", "--keep-intermediates", "main.tex"], cwd=OUT, check=True)
    with tarfile.open(OUT / "arxiv.tar.gz", "w:gz") as t:
        for f in ("main.tex", "main.bbl", "acl.sty", "acl_natbib.bst"):
            t.add(OUT / f, arcname=f)
        for f in figs:
            t.add(OUT / "figs" / f.name, arcname=f"figs/{f.name}")
    pages = re.search(r"Pages:\s+(\d+)", subprocess.run(["pdfinfo", str(OUT / "main.pdf")], capture_output=True,
                                                          text=True).stdout).group(1)
    abstract = tex[tex.index("\\begin{abstract}") + 16:tex.index("\\end{abstract}")]
    (OUT / "ARXIV_SUBMISSION.md").write_text(SUBMISSION.format(pages=pages, figs=len(figs), url=URL, abstract=plain(abstract)))
    print("wrote", OUT / "arxiv.tar.gz", (OUT / "arxiv.tar.gz").stat().st_size, "bytes;", pages, "pages")


def plain(t):
    """LaTeX abstract -> arXiv plain text."""
    t = re.sub(r"Code, results and per-item outputs: \\url\{[^}]*\}\.", "", t)
    t = re.sub(r"\$([0-9.]+)\\times\$", r"\1x", t)
    t = re.sub(r"\$(\d)\\times(\d)\$", r"\1x\2", t)
    t = re.sub(r"\\emph\{([^}]*)\}", r"\1", t)
    t = re.sub(r"\$([a-z])\$", r"\1", t)
    t = re.sub(r"\$(\([a-z],\s*[a-z]\))\$", r"\1", t)        # $(m,n)$
    t = t.replace("--", "-").replace("~", " ")
    assert "\\" not in t and "$" not in t, t
    return " ".join(t.split()) + f" Code: {URL}"


SUBMISSION = """# arXiv submission (generated by paper/build_arxiv.py; fill in at https://arxiv.org/submit)

Upload: paper/arxiv/arxiv.tar.gz (main.tex + main.bbl + acl.sty + acl_natbib.bst + figs/). Compiles with pdflatex.

Title:
Untying Prefill and Decode Loops in Looped Language Models

Authors:
Yang Hu

Primary category: cs.CL (Computation and Language)
Cross-list: cs.LG (Machine Learning)

Comments:
{pages} pages, {figs} figures. Code, per-item results and a script that recomputes every number: {url}

License: CC BY 4.0

Abstract (plain text):
{abstract}
"""


if __name__ == "__main__":
    main()
    # the published copies: paper/untying-prefill-decode-loops.pdf and paper/ARXIV_SUBMISSION.md
    shutil.copy(OUT / "main.pdf", P / "untying-prefill-decode-loops.pdf")
    shutil.copy(OUT / "ARXIV_SUBMISSION.md", P / "ARXIV_SUBMISSION.md")
